#!/usr/bin/env node
// Concatenates every migration, in order, into supabase/dist/full_install.sql
// so a brand-new Supabase project can be set up with one paste in the SQL
// editor. Existing projects run only the migration files they have not run.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../supabase/migrations/", import.meta.url);
const out = new URL("../supabase/dist/", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

const parts = [
  "-- =====================================================================",
  "-- Smart ATS — FULL INSTALL for a NEW, empty Supabase project.",
  "-- Generated by `npm run db:bundle` from supabase/migrations. Do not edit.",
  "-- Existing projects: run only the migration files you have not run yet.",
  `-- Includes: ${files.join(", ")}`,
  "-- =====================================================================",
  "",
];
for (const f of files) {
  parts.push(`-- >>>>>>>>>> ${f}`, readFileSync(new URL(f, dir), "utf8").trimEnd(), "");
}
mkdirSync(out, { recursive: true });
writeFileSync(new URL("full_install.sql", out), parts.join("\n"));
console.log(`supabase/dist/full_install.sql ← ${files.length} migrations`);
